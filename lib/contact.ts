/**
 * 연락처 정리
 *
 * TourAPI 의 tel 필드는 형식이 제각각이다. 실제 데이터에 이런 것들이 들어 있다.
 *   "서울 02-786-0610수원 031-5191-2367화성 070-4202-1017"
 *   "033-808-8007033-808-8009"
 *   "063-454-3912, 3913"
 *   "02-2153-0310, 0311 (12:00~13:00 점심시간)"
 *
 * 전에는 숫자가 아닌 글자를 전부 지워서 tel: 링크를 만들었는데, 그러면
 * 31자리짜리 번호로 전화를 걸게 된다. 살아있는 축제 236건 중 14건이 그랬다.
 * 그래서 문자열에서 "전화번호처럼 생긴 첫 덩어리" 만 뽑아 쓴다.
 */

/**
 * 국내 전화번호 한 덩어리.
 *  - 15xx~18xx 대표번호는 4+4 자리다 (1522-2295). 데이터에 12건 있었다.
 *  - 그 외는 지역번호/휴대폰 3단 (02-1234-5678, 031-290-3622, 010-1234-5678).
 */
const PHONE = /(?:(1[5-8]\d{2})[-.\s]?(\d{4})|(0\d{1,2})[-.\s]?(\d{3,4})[-.\s]?(\d{4}))/;

/**
 * 전화 걸기에 쓸 번호 하나. 못 찾으면 null (그러면 링크를 걸지 않는다).
 * 여러 개가 붙어 있으면 맨 앞의 것을 쓴다 — 보통 주최 측 대표번호가 먼저 온다.
 */
export function dialNumber(tel: string | undefined): string | null {
  const m = PHONE.exec(tel ?? "");
  if (!m) return null;
  return m[1] ? `${m[1]}-${m[2]}` : `${m[3]}-${m[4]}-${m[5]}`;
}

/**
 * 화면에 보여줄 연락처.
 * 원본이 지저분해도 사람이 읽을 수는 있으니 그대로 두되, 붙어 있는 번호 사이는 띄운다.
 */
export function displayTel(tel: string | undefined): string {
  return (tel ?? "")
    // "…8007033-808-8009" → "…8007 033-808-8009".
    // 뒤쪽이 온전한 전화번호일 때만 자른다. 안 그러면 "033-808-8007" 한 개짜리도
    // "033-8 08-8007" 로 쪼개진다 (실제로 그렇게 깨졌다).
    .replace(/(\d{4})((?:0\d{1,2}|1\d{3})[-.\s]?\d{3,4}[-.\s]?\d{4})/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

/** 공식 홈페이지가 없을 때 대신 쓸 네이버 검색 주소 */
export function searchUrl(title: string, region?: string): string {
  const q = [title, region].filter(Boolean).join(" ");
  return `https://search.naver.com/search.naver?query=${encodeURIComponent(q)}`;
}
